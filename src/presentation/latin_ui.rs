/// Render only canonical application message prefixes; names, paths and diagnostics
/// are opaque payloads. Chinese/English behavior stays exactly as before.
pub fn status(language: TextLanguage, message: &str) -> std::borrow::Cow<'_, str> {
    use std::borrow::Cow;
    if language != TextLanguage::Italic {
        return Cow::Borrowed(message);
    }
    let exact = match message {
        "Demo design loaded" => Some("Exemplar navis apertum"),
        "Calculated submitted parameters" => Some("Parametri dati computati"),
        "Design file loaded" => Some("Documentum consilii apertum"),
        "Blended resistance model applied" => Some("Exemplar mixtum resistentiae adhibitum"),
        "Original resistance model restored" => Some("Exemplar originale resistentiae restitutum"),
        "Submitted design pinned as baseline" => Some("Consilium datum ad comparationem servatum"),
        "Comparison cleared" => Some("Comparatio deleta"),
        "Arrangement optimized for submitted design" => Some("Dispositio consilii dati optimata"),
        _ => None,
    };
    if let Some(text) = exact {
        return Cow::Borrowed(text);
    }
    for (prefix, translated) in [
        ("Loaded ", "Apertum: "),
        ("Saved ", "Servatum: "),
        ("Comparing with ", "Comparatio cum "),
        ("Regime applied: ", "Calibratio adhibita: "),
        ("Solved maximum speed: ", "Celeritas maxima computata: "),
        ("Solved range: ", "Spatium navigationis computatum: "),
        ("Scaled displacement: ", "Déplacement adapté: "),
        ("Open failed: ", "Apertura non successit: "),
        ("Save failed: ", "Scriptio non successit: "),
        ("Missing bundled fonts: ", "Typi litterarum desunt: "),
    ] {
        if let Some(payload) = message.strip_prefix(prefix) {
            return Cow::Owned(format!("{translated}{payload}"));
        }
    }
    Cow::Borrowed(message)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn translated_status_preserves_names_paths_and_chinese_behavior() {
        let input = "Loaded Original Saved Engine 中文";
        assert_eq!(
            status(TextLanguage::Italic, input),
            "Apertum: Original Saved Engine 中文"
        );
        assert_eq!(status(TextLanguage::Han, input), input);
        assert_eq!(status(TextLanguage::Germanic, input), input);
        assert_eq!(
            status(TextLanguage::Italic, "Unknown diagnostic"),
            "Unknown diagnostic"
        );
    }
}
